#!/usr/bin/env python3
"""Embed the public native headers for relocatable, compiler-independent exports."""
from pathlib import Path
import argparse

root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
parts = ['/* Generated by scripts/embed_native_runtime.py; do not edit. */\n']
for name in ('native_abi', 'native_runtime'):
    data = (root / 'include' / 'goat' / (name + '.h')).read_text().encode('utf-8')
    parts.append('static const unsigned char ' + name + '_data[] = {\n')
    for offset in range(0, len(data), 16):
        parts.append('    ' + ', '.join(str(b) for b in data[offset:offset + 16]) + ',\n')
    parts.append('};\n')
target = root / 'src/codegen/native_runtime_data.inc'
text = ''.join(parts)
if args.check:
    if not target.exists() or target.read_text() != text:
        raise SystemExit('Native runtime bundle is stale: run scripts/embed_native_runtime.py')
else:
    target.write_text(text)
