"""Compile the frozen v1 schemas into C tables; no runtime schema interpreter.

Run with --check in CI. The generated header is committed, so normal C builds
need neither Python nor the specification files.
"""
import argparse
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('module_schema', ROOT / 'docs/module-format-v1/schema.py')
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)


def generate():
    nodes = []
    definitions = {}

    def add(schema):
        index = len(nodes)
        nodes.append(None)
        node = dict(schema)
        if 'properties' in node:
            node['properties'] = [(key, add(value)) for key, value in node['properties'].items()]
        for key in ('items', 'propertyNames', 'additionalProperties'):
            if isinstance(node.get(key), dict):
                node[key] = add(node[key])
        nodes[index] = node
        return index

    for key, value in module.DEFS.items():
        definitions[key] = add(value)
    roots = {key: add(module.ROOTS[key]) for key in ('gmod', 'module', 'target', 'native')}
    out = ['/* Generated by scripts/generate_module_json_schema.py. Do not edit. */',
           '/* clang-format off */', '#pragma once', '', f'static const json_schema schemas[{len(nodes)}];', '']
    patterns = {
        module.NAME['pattern']: 'PATTERN_NAME', module.HASH['pattern']: 'PATTERN_HASH',
        module.ROOTS['gmod']['properties']['native']['properties']['target']['pattern']: 'PATTERN_TARGET',
        module.DEFS['variant']['properties']['library']['pattern']: 'PATTERN_LIBRARY',
        module.DEFS['specialization']['properties']['symbol']['pattern']: 'PATTERN_SYMBOL',
    }
    for i, n in enumerate(nodes):
        if 'properties' in n:
            out.append(f'static const json_field fields_{i}[] = {{')
            for key, child in n['properties']:
                required = 'true' if key in n.get('required', []) else 'false'
                out.append(f'    {{"{key}", &schemas[{child}], {required}}},')
            out.append('};')
        if 'enum' in n or 'const' in n:
            values = n.get('enum', [n.get('const')])
            out.append(f'static const json_literal literals_{i}[] = {{')
            for v in values:
                typ = 'STRING' if isinstance(v, str) else 'BOOL' if isinstance(v, bool) else 'INTEGER'
                value = v if isinstance(v, str) else json.dumps(v)
                out.append(f'    {{JSON_{typ}, {json.dumps(value)}}},')
            out.append('};')
    out.append(f'static const json_schema schemas[{len(nodes)}] = {{')
    for i, n in enumerate(nodes):
        fields = []
        if '$ref' in n:
            fields.append(f'.reference = &schemas[{definitions[n["$ref"].split("/")[-1]]}]')
        types = n.get('type', [])
        if isinstance(types, str):
            types = [types]
        if types:
            fields.append('.types = ' + ' | '.join('JSON_' + t.upper().replace('BOOLEAN', 'BOOL') for t in types))
        if 'properties' in n:
            fields += [f'.fields = fields_{i}', f'.field_count = {len(n["properties"])}']
        for key, field in [('items', 'items'), ('propertyNames', 'keys'), ('additionalProperties', 'extra')]:
            if type(n.get(key)) is int:
                fields.append(f'.{field} = &schemas[{n[key]}]')
        if n.get('additionalProperties') is False:
            fields.append('.closed = true')
        if 'minimum' in n or 'maximum' in n:
            lo, hi = n.get('minimum', -(1 << 63)), n.get('maximum', (1 << 63)-1)
            fields += ['.bounded = true', f'.minimum = {"INT64_MIN" if lo == -(1 << 63) else "INT64_C(" + str(lo) + ")"}',
                       f'.maximum = INT64_C({hi})']
        for key, field in [('minItems', 'min_count'), ('maxItems', 'max_count'),
                           ('minLength', 'min_length'), ('maxLength', 'max_length')]:
            if key in n:
                fields.append(f'.{field} = {n[key]}')
        if n.get('uniqueItems'):
            fields.append('.unique = true')
        if 'pattern' in n:
            fields.append('.pattern = ' + patterns[n['pattern']])
        if 'enum' in n or 'const' in n:
            fields += [f'.literals = literals_{i}', f'.literal_count = {len(n.get("enum", [None]))}']
        if type(n.get('const')) is int and n['const'] == 1:
            fields.append('.format_version = true')
        out.append('    {' + ', '.join(fields) + '},')
    out += ['};', '', f'#define GMOD_SCHEMA (&schemas[{roots["gmod"]}])',
            f'#define METADATA_SCHEMA (&schemas[{roots["module"]}])',
            f'#define TARGET_SCHEMA (&schemas[{roots["target"]}])',
            f'#define NATIVE_SCHEMA (&schemas[{roots["native"]}])', '']
    return '\n'.join(out)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'src/module/module_json_schema.h'
    content = generate()
    if args.check:
        if path.read_text() != content:
            raise SystemExit('Stale module_json_schema.h; regenerate it')
    else:
        path.write_text(content)
