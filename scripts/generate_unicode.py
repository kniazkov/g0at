#!/usr/bin/env python3
"""Reproduce Unicode 17.0.0 tables from the vendored UCD; no network access."""
from pathlib import Path
import hashlib
root = Path(__file__).resolve().parents[1]
ucd = root / 'third_party/unicode/17.0.0'
upper, lower = {}, {}
for line in (ucd / 'UnicodeData.txt').read_text().splitlines():
    f = line.split(';'); c = int(f[0],16)
    if f[12]: upper[c] = [int(f[12],16)]
    if f[13]: lower[c] = [int(f[13],16)]
full_upper, full_lower = upper.copy(), lower.copy()
for line in (ucd / 'SpecialCasing.txt').read_text().splitlines():
    f = line.split('#')[0].strip().split(';')
    if len(f) < 5 or f[4].strip(): continue
    c = int(f[0],16)
    full_lower[c] = [int(x,16) for x in f[1].split()]
    full_upper[c] = [int(x,16) for x in f[3].split()]
props = {'Cased': [], 'Case_Ignorable': [], 'White_Space': []}
for name in ['DerivedCoreProperties.txt', 'PropList.txt']:
    for line in (ucd / name).read_text().splitlines():
        f = line.split('#')[0].strip().split(';')
        if len(f) != 2 or f[1].strip() not in props: continue
        bounds = f[0].strip().split('..')
        props[f[1].strip()].append((int(bounds[0],16),int(bounds[-1],16)))
out = [
    '/* Generated by scripts/generate_unicode.py; Unicode 17.0.0. Do not edit.',
    ' * Implementation-only Unicode tables, included after their private types.',
    ' * Intentional project exception: no #pragma once and no include guard.',
    ' * Keep generated table formatting reproducible without clang-format.',
    ' */',
    '// clang-format off',
]
for name, table in [('simple_upper',upper),('simple_lower',lower),('full_upper',full_upper),('full_lower',full_lower)]:
    out.append(f'static const case_entry_t {name}[] = {{')
    for c, seq in sorted(table.items()):
        out.append('    {0x%x, %d, {%s}},' % (c,len(seq),','.join('0x%x'%x for x in seq)))
    out.append('};')
for name, spans in props.items():
    out.append(f'static const scalar_range_t {name}[] = {{')
    out.extend('    {0x%x,0x%x},' % x for x in sorted(spans))
    out.append('};')
(root/'lib/strings/unicode_data.h').write_text('\n'.join(out)+'\n')
manifest = ''.join(f'{hashlib.sha256(p.read_bytes()).hexdigest()}  {p.name}\n' for p in sorted(ucd.glob('*.txt')))
(ucd/'SHA256SUMS').write_text(manifest)
